/**
 * The archive (`src/data/`) as a standard group in the server's database (issue #6): a plain
 * group like any other, whose members are the archive's players, with every year already
 * closed, its result and everyone's prediction. Nothing special about it: its owner is the
 * Google account with the owner's email, and the others take their names by joining with
 * the owner's invitation; the group goes on with 2027 and beyond.
 *
 * Pure: the raw files in, SQL out. Imports nothing, so plain Node can run it
 * (`node scripts/seed-archive.ts`); a test runs the SQL against the real migrations.
 */
import { createHash } from 'node:crypto';

/** Fixed, not secret: the address of the invitation is this id plus the invitation's secret. */
export const ARCHIVE_GROUP_ID = 'douze_archive_group_01';
export const ARCHIVE_GROUP_NAME = 'החברים';
/** The archive player who owns the group. */
const OWNER = 'matan';
/** Replaced by the owner's email when the seed is applied (it is never in the repository). */
export const OWNER_EMAIL_PLACEHOLDER = '__OWNER_EMAIL__';
/** An archived stage is said to have closed at the end of May of its year. */
const closedAt = (year: number) => Date.UTC(year, 4, 31, 23, 59);
const CREATED_AT = Date.UTC(2026, 10, 28);
const QUALIFIERS = 10;

interface Player {
  id: string;
  name: { he: string; en: string };
}
interface Semi {
  countries: string[];
  qualifiers: string[] | null;
  predictions: { player: string; picks: string[]; reserve: string | null }[];
}
interface Edition {
  year: number;
  finalists: string[];
  result: string[] | null;
  joker?: boolean;
  predictions: { player: string; order: string[]; joker?: string }[];
  semis: Semi[];
}

const quote = (text: string) => `'${text.replaceAll("'", "''")}'`;
const list = (items: readonly string[] | null) => (items ? quote(JSON.stringify(items)) : 'NULL');

/** A member's id from the group and the archive's own id: the same on every run. */
function memberId(player: string): string {
  return createHash('sha256')
    .update(`${ARCHIVE_GROUP_ID}:${player}`)
    .digest('base64url')
    .slice(0, 22);
}

export function archiveSeedSql(players: readonly Player[], editions: readonly Edition[]): string {
  const name = new Map(players.map((p) => [p.id, p.name.he]));
  const used = new Set(
    editions.flatMap((e) => [
      ...e.predictions.map((p) => p.player),
      ...e.semis.flatMap((s) => s.predictions.map((p) => p.player)),
    ]),
  );
  const lines: string[] = [
    '-- Generated by scripts/archiveSeed.ts from src/data/: do not edit; run `node scripts/seed-archive.ts`.',
    '-- Every statement is INSERT OR IGNORE: applying it again changes nothing that already exists.',
    // The invitation starts as a hash of nothing anyone knows: the owner makes a link in the app.
    `INSERT OR IGNORE INTO groups (id, name, invite_hash, created_at) VALUES (${quote(ARCHIVE_GROUP_ID)}, ${quote(ARCHIVE_GROUP_NAME)}, lower(hex(randomblob(32))), ${CREATED_AT});`,
  ];
  for (const id of [...used].sort()) {
    const owner = id === OWNER;
    lines.push(
      `INSERT OR IGNORE INTO members (id, group_id, name, role, joined_at, claim_email) VALUES (${quote(memberId(id))}, ${quote(ARCHIVE_GROUP_ID)}, ${quote(name.get(id) ?? id)}, ${quote(owner ? 'owner' : 'member')}, ${CREATED_AT}, ${owner ? quote(OWNER_EMAIL_PLACEHOLDER) : 'NULL'});`,
    );
  }
  const stage = (
    year: number,
    kind: string,
    countries: string[],
    joker: boolean,
    result: string[] | null,
  ) =>
    lines.push(
      `INSERT OR IGNORE INTO stages (group_id, year, stage, countries, lock_at, joker, result) VALUES (${quote(ARCHIVE_GROUP_ID)}, ${year}, ${quote(kind)}, ${list(countries)}, ${closedAt(year)}, ${joker ? 1 : 0}, ${list(result)});`,
    );
  const entry = (year: number, kind: string, player: string, body: object, complete: boolean) =>
    lines.push(
      `INSERT OR IGNORE INTO entries (group_id, year, stage, member_id, body, complete, updated_at) VALUES (${quote(ARCHIVE_GROUP_ID)}, ${year}, ${quote(kind)}, ${quote(memberId(player))}, ${quote(JSON.stringify(body))}, ${complete ? 1 : 0}, ${CREATED_AT});`,
    );
  for (const e of [...editions].sort((a, b) => a.year - b.year)) {
    if (e.finalists.length >= 2) {
      stage(e.year, 'final', e.finalists, !!e.joker, e.result);
      for (const p of e.predictions)
        entry(
          e.year,
          'final',
          p.player,
          { order: p.order, joker: p.joker ?? null },
          p.order.length === e.finalists.length,
        );
    }
    e.semis.forEach((semi, i) => {
      if (semi.countries.length < 2) return;
      const kind = i === 0 ? 'semi-1' : 'semi-2';
      stage(e.year, kind, semi.countries, false, semi.qualifiers);
      const need = Math.max(0, Math.min(QUALIFIERS, semi.countries.length - 1));
      for (const p of semi.predictions)
        entry(
          e.year,
          kind,
          p.player,
          { picks: p.picks, reserve: p.reserve },
          p.picks.length === need && p.reserve !== null,
        );
    });
  }
  return `${lines.join('\n')}\n`;
}
